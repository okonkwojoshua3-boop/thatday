/**
 * The fuel price on a date: the regulated price in force that day, or that
 * year's average (filled along a growth curve across missing years). Null
 * before a country's records start. `year` is the year the price is from.
 */
export function fuelPrice(country: string, date: string): { key: string; price: number; year: number } | null {
  const series = FUEL[country === 'world' ? 'us' : country]
  if (!series) return null
  const year = Number(date.slice(0, 4))

  if (series.steps) {
    const steps = series.steps
    if (date < steps[0][0]) return null
    let at = steps[0]
    for (const s of steps) if (date >= s[0]) at = s
    return { key: series.key, price: at[1], year: Math.max(Number(at[0].slice(0, 4)), Math.min(year, new Date().getFullYear())) }
  }

  const annual = series.annual!
  const years = Object.keys(annual).map(Number).sort((a, b) => a - b)
  if (year < years[0]) return null
  if (annual[year] !== undefined) return { key: series.key, price: annual[year], year }
  const last = years[years.length - 1]
  if (year > last) return { key: series.key, price: annual[last], year: last }
  const lo = years.filter(y => y < year).pop()!
  const hi = years.find(y => y > year)!
  const price = annual[lo] * Math.pow(annual[hi] / annual[lo], (year - lo) / (hi - lo))
  return { key: series.key, price: parseFloat(price.toFixed(price < 1 ? 3 : 2)), year }
}
